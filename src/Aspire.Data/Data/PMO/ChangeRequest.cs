namespace Aspire.Data;

[Attr(DomainFolder = "PMO", Abbrv = "CR", SubList = true)]
public class ChangeRequest : EntityWithLineItems
{
    [Attr(Parent = true)]
    public long? ProjectId { get; set; }

    [NotMapped]
    public virtual Project? Project { get; set; }

    public DateTime? IssueDate { get; set; }
    public DateTime? ApprovalDate { get; set; }

    public ChangeRequest() { }
    public ChangeRequest(long tnantId, string name, long? projId, decimal amount, long? curId, long? ratId)
    {
        TenantId = tnantId;
        
        this.Name = name;
        this.ProjectId = projId;
        this.calc_Amount_val = amount;
        Amount_cur = curId;
    }
}

