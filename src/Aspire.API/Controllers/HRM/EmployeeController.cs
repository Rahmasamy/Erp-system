    [HttpPost("GetAll")]
    public async Task<IActionResult> GetAll([FromBody] FilteringModel? filteringModel)
    {
        try
        {
            PaginationModel<EmployeeDTO> Objs = await _genericRepository.GetAllJoins(filteringModel);
            List<EmployeeTeamDTO> ObjWithTeam_List = new List<EmployeeTeamDTO>();
            foreach (EmployeeDTO Obj in Objs.Items)
            {
                EmployeeTeamDTO ObjWithTeam = _mapper.Map<EmployeeTeamDTO>(Obj);

                List<ApplicationUser> StkHldrs = StakeholdersService.Stakeholders(Obj, context);
                foreach (ApplicationUser StkHldr in StkHldrs)
                    ObjWithTeam.Stakeholders.Add(new TeamMemberAvatarDTO() { Name = StkHldr.Name, PhotoUrl = @"/avatars/" + StkHldr.Id + ".png" });

                ObjWithTeam_List.Add(ObjWithTeam);
            }

            PaginationModel<EmployeeTeamDTO> Objs2 = new PaginationModel<EmployeeTeamDTO>(ObjWithTeam_List, Objs.PageNumber, Objs.PageSize, Objs.TotalItems, Objs.Aggregates);
            return Ok(Objs2);

        }
        catch (Exception ex)
        {
            return Ok(new { severity = "error", summary = "Server Exception", message = ex.Message });
        }
    }

